// LLVM IR backend. Walks the type-checked AST and writes textual LLVM IR.
//   * int -> i64, float -> double, bool -> i1; dna/rna/protein/string/motif/list -> ptr
//   * every motif DFA becomes constant tables plus a native @motifN_match function
//   * sequence/list helpers and the scan loop live in runtime/biolang_rt.c
#include "codegen.hpp"
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <map>
#include <sstream>
#include <vector>
#include "motif.hpp"
#include "typechecker.hpp"

namespace {

struct V { std::string v; Type t; };

bool isNum(Type t) { return t == Type::INT || t == Type::FLOAT; }

Type declType(TokType t) {
    switch (t) {
        case TokType::KW_DNA:     return Type::DNA;
        case TokType::KW_RNA:     return Type::RNA;
        case TokType::KW_PROTEIN: return Type::PROTEIN;
        case TokType::KW_MOTIF:   return Type::MOTIF;
        case TokType::KW_INT:     return Type::INT;
        case TokType::KW_FLOAT:   return Type::FLOAT;
        case TokType::KW_STRING:  return Type::STRING;
        default:                  return Type::BOOL;
    }
}

const char* irType(Type t) {
    switch (t) {
        case Type::INT:   return "i64";
        case Type::FLOAT: return "double";
        case Type::BOOL:  return "i1";
        default:          return "ptr";
    }
}

std::string dbl(double d) {
    uint64_t b;
    std::memcpy(&b, &d, 8);
    char buf[32];
    std::snprintf(buf, sizeof buf, "0x%016llX", static_cast<unsigned long long>(b));
    return buf;
}

std::string escape(const std::string& s) {
    std::string o;
    char buf[8];
    for (unsigned char c : s) {
        if (c >= 32 && c < 127 && c != '"' && c != '\\') o += static_cast<char>(c);
        else { std::snprintf(buf, sizeof buf, "\\%02X", c); o += buf; }
    }
    return o;
}

class Gen {
public:
    std::string run(const Program& prog) {
        scopes_.emplace_back();
        for (const auto& s : prog.stmts) stmt(*s);
        std::ostringstream out;
        out << "; generated by BioLang (--emit-llvm). Link with runtime/biolang_rt.c\n"
               "%Motif = type { ptr, i32, i32, i32, ptr, ptr, ptr, ptr, ptr, ptr, ptr }\n\n"
               "declare void @bl_chk_div_i(i64, i32, i32)\n"
               "declare void @bl_chk_div_f(double, i32, i32)\n"
               "declare i64 @bl_len(ptr)\n"
               "declare ptr @bl_concat(ptr, ptr)\n"
               "declare ptr @bl_slice(ptr, i64, i64, i32, i32)\n"
               "declare i32 @bl_str_eq(ptr, ptr)\n"
               "declare ptr @bl_transcribe(ptr)\n"
               "declare ptr @bl_translate(ptr)\n"
               "declare ptr @bl_revcomp(ptr)\n"
               "declare double @bl_gc(ptr)\n"
               "declare ptr @bl_load_fasta(ptr, i32, i32)\n"
               "declare i64 @bl_list_len(ptr)\n"
               "declare i64 @bl_list_at(ptr, i64)\n"
               "declare i64 @bl_list_get(ptr, i64, i32, i32)\n"
               "declare ptr @bl_find_all(ptr, ptr)\n"
               "declare i64 @bl_match_end(ptr, ptr, i64, i32, i32)\n"
               "declare void @bl_print_int(i64)\n"
               "declare void @bl_print_float(double)\n"
               "declare void @bl_print_bool(i32)\n"
               "declare void @bl_print_str(ptr)\n"
               "declare void @bl_print_motif(ptr)\n"
               "declare void @bl_print_list(ptr)\n\n"
            << globals_.str()
            << "\ndefine i32 @main() {\nentry:\n" << allocas_.str() << body_.str()
            << "  ret i32 0\n}\n";
        return out.str();
    }

private:
    struct Var { std::string slot; Type t; };
    std::ostringstream globals_, body_, allocas_;
    std::vector<std::map<std::string, Var>> scopes_;
    int tmp_ = 0, lbl_ = 0, str_ = 0, motif_ = 0, slot_ = 0;

    std::string T() { return "%t" + std::to_string(++tmp_); }
    void emit(const std::string& s) { body_ << "  " << s << "\n"; }
    void label(const std::string& l) { body_ << l << ":\n"; }
    static std::string pos(const Node& n) {
        return "i32 " + std::to_string(n.line) + ", i32 " + std::to_string(n.col);
    }

    Var* lookup(const std::string& name) {
        for (auto it = scopes_.rbegin(); it != scopes_.rend(); ++it) {
            auto f = it->find(name);
            if (f != it->end()) return &f->second;
        }
        return nullptr;
    }
    Var declare(const std::string& name, Type t) {
        Var v{"%v" + std::to_string(++slot_) + "." + name, t};
        allocas_ << "  " << v.slot << " = alloca " << irType(t) << "\n";
        scopes_.back()[name] = v;
        return v;
    }

    std::string strConst(const std::string& s) {
        std::string g = "@.str." + std::to_string(++str_);
        size_t n = s.size();
        globals_ << g << " = private unnamed_addr constant { i64, [" << n + 1 << " x i8] } { i64 " << n
                 << ", [" << n + 1 << " x i8] c\"" << escape(s) << "\\00\" }\n";
        return g;
    }

    template <class F>
    static std::string table(const char* ty, size_t n, F at) {
        std::string s = "[" + std::to_string(n) + " x " + ty + "] [";
        for (size_t i = 0; i < n; i++) s += (i ? ", " : "") + std::string(ty) + " " + std::to_string(at(i));
        return s + "]";
    }

    // Emits the DFA tables, the native match function and the %Motif descriptor.
    std::string motif(const RegexLit& r) {
        if (!r.dfa) throw CodegenError{"motif was not compiled (run the type checker first)", r.line, r.col};
        const Dfa& d = *r.dfa;
        int id = ++motif_;
        std::string m = "@m" + std::to_string(id);
        const int K = d.numClasses;
        const size_t S = static_cast<size_t>(d.numStates());
        bool rev = d.ensureReverse();

        globals_ << m << ".cm = private constant "
                 << table("i8", 256, [&](size_t i) { return d.classMap[i]; }) << "\n";
        globals_ << m << ".sb = private constant "
                 << table("i8", 256, [&](size_t i) { return d.startByte[i] ? 1 : 0; }) << "\n";
        globals_ << m << ".tr = private constant "
                 << table("i32", S * K, [&](size_t i) { return d.trans[i]; }) << "\n";
        globals_ << m << ".ac = private constant "
                 << table("i8", S, [&](size_t i) { return d.accepting[i] ? 1 : 0; }) << "\n";
        if (rev) {
            globals_ << m << ".rt = private constant "
                     << table("i32", d.rtrans.size(), [&](size_t i) { return d.rtrans[i]; }) << "\n";
            globals_ << m << ".ra = private constant "
                     << table("i8", d.racc.size(), [&](size_t i) { return d.racc[i] ? 1 : 0; }) << "\n";
        }

        // Anchored forward DFA run: two table lookups per input byte, no backtracking.
        std::string f = m + ".match";
        globals_ << "define i64 " << "@m" << id << ".match(ptr %s, i64 %n, i64 %from, ptr %work) {\n"
                 << "entry:\n  br label %loop\n"
                 << "loop:\n"
                 << "  %state = phi i32 [ " << d.start << ", %entry ], [ %ns, %step ]\n"
                 << "  %j = phi i64 [ %from, %entry ], [ %j2, %step ]\n"
                 << "  %last = phi i64 [ -1, %entry ], [ %last2, %step ]\n"
                 << "  %more = icmp slt i64 %j, %n\n"
                 << "  br i1 %more, label %body, label %exit\n"
                 << "body:\n"
                 << "  %p = getelementptr i8, ptr %s, i64 %j\n"
                 << "  %b = load i8, ptr %p\n"
                 << "  %bz = zext i8 %b to i64\n"
                 << "  %cp = getelementptr i8, ptr " << m << ".cm, i64 %bz\n"
                 << "  %c8 = load i8, ptr %cp\n"
                 << "  %c = zext i8 %c8 to i32\n"
                 << "  %row = mul i32 %state, " << K << "\n"
                 << "  %idx = add i32 %row, %c\n"
                 << "  %idx64 = zext i32 %idx to i64\n"
                 << "  %tp = getelementptr i32, ptr " << m << ".tr, i64 %idx64\n"
                 << "  %ns = load i32, ptr %tp\n"
                 << "  %dead = icmp slt i32 %ns, 0\n"
                 << "  br i1 %dead, label %exit, label %step\n"
                 << "step:\n"
                 << "  %j2 = add i64 %j, 1\n"
                 << "  %ns64 = zext i32 %ns to i64\n"
                 << "  %ap = getelementptr i8, ptr " << m << ".ac, i64 %ns64\n"
                 << "  %a8 = load i8, ptr %ap\n"
                 << "  %isacc = icmp ne i8 %a8, 0\n"
                 << "  %last2 = select i1 %isacc, i64 %j2, i64 %last\n"
                 << (d.shortest ? "  br i1 %isacc, label %exit, label %loop\n" : "  br label %loop\n")
                 << "exit:\n"
                 << "  %jf = phi i64 [ %j, %loop ], [ %j, %body ]"
                 << (d.shortest ? ", [ %j2, %step ]" : "") << "\n"
                 << "  %lf = phi i64 [ %last, %loop ], [ %last, %body ]"
                 << (d.shortest ? ", [ %last2, %step ]" : "") << "\n"
                 << "  %w0 = load i64, ptr %work\n"
                 << "  %used = sub i64 %jf, %from\n"
                 << "  %w1 = add i64 %w0, %used\n"
                 << "  store i64 %w1, ptr %work\n"
                 << "  ret i64 %lf\n}\n";

        std::string pat = strConst(r.pattern);
        globals_ << m << " = private constant %Motif { ptr " << pat << ", i32 " << K << ", i32 " << d.start
                 << ", i32 " << (d.shortest ? 1 : 0) << ", ptr " << m << ".cm, ptr " << m << ".tr, ptr "
                 << m << ".ac, ptr " << m << ".sb, ptr " << (rev ? m + ".rt" : std::string("null"))
                 << ", ptr " << (rev ? m + ".ra" : std::string("null")) << ", ptr " << f << " }\n\n";
        return m;
    }

    V toFloat(V v) {
        if (v.t != Type::INT) return v;
        std::string t = T();
        emit(t + " = sitofp i64 " + v.v + " to double");
        return {t, Type::FLOAT};
    }

    V expr(const Expr& e) {
        if (const auto* s = dynamic_cast<const StringLit*>(&e)) return {strConst(s->value), Type::STRING};
        if (const auto* r = dynamic_cast<const RegexLit*>(&e)) return {motif(*r), Type::MOTIF};
        if (const auto* n = dynamic_cast<const NumberLit*>(&e)) {
            if (n->text.find('.') != std::string::npos) return {dbl(std::stod(n->text)), Type::FLOAT};
            return {std::to_string(std::stoll(n->text)), Type::INT};
        }
        if (const auto* id = dynamic_cast<const Ident*>(&e)) {
            Var* v = lookup(id->name);
            if (!v) throw CodegenError{"undefined variable '" + id->name + "'", id->line, id->col};
            std::string t = T();
            emit(t + " = load " + irType(v->t) + ", ptr " + v->slot);
            return {t, v->t};
        }
        if (const auto* b = dynamic_cast<const Binary*>(&e)) return binary(*b);
        if (const auto* ix = dynamic_cast<const Index*>(&e)) {
            V base = expr(*ix->base), k = expr(*ix->idx);
            std::string t = T();
            emit(t + " = call i64 @bl_list_get(ptr " + base.v + ", i64 " + k.v + ", " + pos(*ix) + ")");
            return {t, Type::INT};
        }
        if (const auto* sl = dynamic_cast<const Slice*>(&e)) {
            V base = expr(*sl->base);
            std::string lo = "0", hi;
            if (sl->lo) lo = expr(*sl->lo).v;
            if (sl->hi) hi = expr(*sl->hi).v;
            else { hi = T(); emit(hi + " = call i64 @bl_len(ptr " + base.v + ")"); }
            std::string t = T();
            emit(t + " = call ptr @bl_slice(ptr " + base.v + ", i64 " + lo + ", i64 " + hi + ", " + pos(*sl) + ")");
            return {t, base.t};
        }
        if (const auto* c = dynamic_cast<const Call*>(&e)) return call(*c);
        throw CodegenError{"unsupported expression", e.line, e.col};
    }

    V binary(const Binary& b) {
        V l = expr(*b.lhs), r = expr(*b.rhs);
        const std::string& op = b.op;
        std::string t = T();

        if (op == "==" || op == "!=") {
            bool eq = op == "==";
            if (isNum(l.t) && isNum(r.t)) {
                if (l.t == Type::INT && r.t == Type::INT) {
                    emit(t + " = icmp " + (eq ? "eq" : "ne") + " i64 " + l.v + ", " + r.v);
                } else {
                    V x = toFloat(l), y = toFloat(r);
                    emit(t + " = fcmp " + (eq ? "oeq" : "une") + " double " + x.v + ", " + y.v);
                }
            } else if (l.t == Type::BOOL) {
                emit(t + " = icmp " + (eq ? "eq" : "ne") + " i1 " + l.v + ", " + r.v);
            } else if (l.t == Type::DNA || l.t == Type::RNA || l.t == Type::PROTEIN || l.t == Type::STRING) {
                std::string c = T();
                emit(c + " = call i32 @bl_str_eq(ptr " + l.v + ", ptr " + r.v + ")");
                emit(t + " = icmp " + (eq ? "ne" : "eq") + " i32 " + c + ", 0");
            } else {
                throw CodegenError{"the LLVM backend cannot compare " + std::string(typeName(l.t)) + " values", b.line, b.col};
            }
            return {t, Type::BOOL};
        }
        if (op == "<" || op == ">" || op == "<=" || op == ">=") {
            if (l.t == Type::INT && r.t == Type::INT) {
                const char* cc = op == "<" ? "slt" : op == ">" ? "sgt" : op == "<=" ? "sle" : "sge";
                emit(t + " = icmp " + cc + " i64 " + l.v + ", " + r.v);
            } else {
                V x = toFloat(l), y = toFloat(r);
                const char* cc = op == "<" ? "olt" : op == ">" ? "ogt" : op == "<=" ? "ole" : "oge";
                emit(t + " = fcmp " + std::string(cc) + " double " + x.v + ", " + y.v);
            }
            return {t, Type::BOOL};
        }
        if (op == "+" && !isNum(l.t)) {  // sequence / string concatenation
            emit(t + " = call ptr @bl_concat(ptr " + l.v + ", ptr " + r.v + ")");
            return {t, l.t};
        }
        const char* iop = op == "+" ? "add" : op == "-" ? "sub" : op == "*" ? "mul" : "sdiv";
        const char* fop = op == "+" ? "fadd" : op == "-" ? "fsub" : op == "*" ? "fmul" : "fdiv";
        if (l.t == Type::INT && r.t == Type::INT) {
            if (op == "/") emit("call void @bl_chk_div_i(i64 " + r.v + ", " + pos(b) + ")");
            emit(t + " = " + iop + " i64 " + l.v + ", " + r.v);
            return {t, Type::INT};
        }
        V x = toFloat(l), y = toFloat(r);
        if (op == "/") emit("call void @bl_chk_div_f(double " + y.v + ", " + pos(b) + ")");
        emit(t + " = " + fop + " double " + x.v + ", " + y.v);
        return {t, Type::FLOAT};
    }

    V call(const Call& c) {
        const std::string& f = c.callee;
        std::string t = T();
        if (f == "find_all") {
            const auto* in = static_cast<const InExpr*>(c.args[0].get());
            V m = expr(*in->needle), s = expr(*in->haystack);
            emit(t + " = call ptr @bl_find_all(ptr " + m.v + ", ptr " + s.v + ")");
            return {t, Type::LIST_INT};
        }
        if (f == "match_end") {
            const auto* in = static_cast<const InExpr*>(c.args[0].get());
            V m = expr(*in->needle), s = expr(*in->haystack), p = expr(*c.args[1]);
            emit(t + " = call i64 @bl_match_end(ptr " + m.v + ", ptr " + s.v + ", i64 " + p.v + ", " + pos(c) + ")");
            return {t, Type::INT};
        }
        V a = expr(*c.args[0]);
        if (f == "load_fasta") { emit(t + " = call ptr @bl_load_fasta(ptr " + a.v + ", " + pos(c) + ")"); return {t, Type::DNA}; }
        if (f == "count")      { emit(t + " = call i64 @bl_list_len(ptr " + a.v + ")"); return {t, Type::INT}; }
        if (f == "len")        { emit(t + " = call i64 @bl_len(ptr " + a.v + ")"); return {t, Type::INT}; }
        if (f == "gc_content") { emit(t + " = call double @bl_gc(ptr " + a.v + ")"); return {t, Type::FLOAT}; }
        if (f == "transcribe") { emit(t + " = call ptr @bl_transcribe(ptr " + a.v + ")"); return {t, Type::RNA}; }
        if (f == "translate")  { emit(t + " = call ptr @bl_translate(ptr " + a.v + ")"); return {t, Type::PROTEIN}; }
        if (f == "revcomp")    { emit(t + " = call ptr @bl_revcomp(ptr " + a.v + ")"); return {t, Type::DNA}; }
        throw CodegenError{"unknown function '" + f + "'", c.line, c.col};
    }

    void block(const std::vector<StmtPtr>& body) {
        scopes_.emplace_back();
        for (const auto& s : body) stmt(*s);
        scopes_.pop_back();
    }

    void stmt(const Stmt& s) {
        if (const auto* d = dynamic_cast<const VarDecl*>(&s)) {
            Type target = declType(d->type);
            V v = expr(*d->init);          // evaluated before the name exists, as in the checker
            if (target == Type::FLOAT) v = toFloat(v);
            Var slot = declare(d->name, target);
            emit(std::string("store ") + irType(target) + " " + v.v + ", ptr " + slot.slot);
        } else if (const auto* a = dynamic_cast<const Assign*>(&s)) {
            Var* slot = lookup(a->name);
            if (!slot) throw CodegenError{"undefined variable '" + a->name + "'", a->line, a->col};
            V v = expr(*a->value);
            if (slot->t == Type::FLOAT) v = toFloat(v);
            emit(std::string("store ") + irType(slot->t) + " " + v.v + ", ptr " + slot->slot);
        } else if (const auto* p = dynamic_cast<const PrintStmt*>(&s)) {
            V v = expr(*p->expr);
            switch (v.t) {
                case Type::INT:   emit("call void @bl_print_int(i64 " + v.v + ")"); break;
                case Type::FLOAT: emit("call void @bl_print_float(double " + v.v + ")"); break;
                case Type::BOOL: {
                    std::string z = T();
                    emit(z + " = zext i1 " + v.v + " to i32");
                    emit("call void @bl_print_bool(i32 " + z + ")");
                    break;
                }
                case Type::MOTIF:    emit("call void @bl_print_motif(ptr " + v.v + ")"); break;
                case Type::LIST_INT: emit("call void @bl_print_list(ptr " + v.v + ")"); break;
                default:             emit("call void @bl_print_str(ptr " + v.v + ")"); break;
            }
        } else if (const auto* e = dynamic_cast<const ExprStmt*>(&s)) {
            expr(*e->expr);
        } else if (const auto* i = dynamic_cast<const IfStmt*>(&s)) {
            V c = expr(*i->cond);
            int id = ++lbl_;
            std::string th = "if.then" + std::to_string(id), el = "if.else" + std::to_string(id),
                        en = "if.end" + std::to_string(id);
            bool hasElse = !i->elseBody.empty();
            emit("br i1 " + c.v + ", label %" + th + ", label %" + (hasElse ? el : en));
            label(th);
            block(i->thenBody);
            emit("br label %" + en);
            if (hasElse) {
                label(el);
                block(i->elseBody);
                emit("br label %" + en);
            }
            label(en);
        } else if (const auto* f = dynamic_cast<const ForStmt*>(&s)) {
            V list = expr(*f->iter);
            std::string n = T();
            emit(n + " = call i64 @bl_list_len(ptr " + list.v + ")");
            scopes_.emplace_back();
            Var idx = declare("$idx", Type::INT);
            Var var = declare(f->var, Type::INT);
            emit("store i64 0, ptr " + idx.slot);
            int id = ++lbl_;
            std::string lc = "for.cond" + std::to_string(id), lb = "for.body" + std::to_string(id),
                        le = "for.end" + std::to_string(id);
            emit("br label %" + lc);
            label(lc);
            std::string i0 = T(), cond = T();
            emit(i0 + " = load i64, ptr " + idx.slot);
            emit(cond + " = icmp slt i64 " + i0 + ", " + n);
            emit("br i1 " + cond + ", label %" + lb + ", label %" + le);
            label(lb);
            std::string v = T();
            emit(v + " = call i64 @bl_list_at(ptr " + list.v + ", i64 " + i0 + ")");
            emit("store i64 " + v + ", ptr " + var.slot);
            block(f->body);
            std::string i1 = T(), i2 = T();
            emit(i1 + " = load i64, ptr " + idx.slot);
            emit(i2 + " = add i64 " + i1 + ", 1");
            emit("store i64 " + i2 + ", ptr " + idx.slot);
            emit("br label %" + lc);
            label(le);
            scopes_.pop_back();
        }
    }
};

}  // namespace

std::string generateLLVM(const Program& program) {
    return Gen().run(program);
}
